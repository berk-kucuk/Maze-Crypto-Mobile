#!/usr/bin/env python3
"""Convert the Phosphor icons in tools/phosphor (MIT, see LICENSE there) to
Android vector drawables named ic_<name>.xml. Every Phosphor icon is one
filled path on a 256-unit grid, so the conversion is a copy of that path."""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "app" / "src" / "main" / "res" / "drawable"

for svg in sorted((HERE / "phosphor").glob("*.svg")):
    d = re.search(r'<path d="([^"]+)"', svg.read_text()).group(1)
    name = "ic_" + svg.stem.replace("-", "_")
    (OUT / f"{name}.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f'<!-- Phosphor icon "{svg.stem}" (MIT). Generated by tools/phosphor_to_vector.py. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp" android:height="24dp"\n'
        '    android:viewportWidth="256" android:viewportHeight="256">\n'
        f'    <path android:fillColor="#FFFFFFFF" android:pathData="{d}" />\n'
        '</vector>\n')
print("ok")
