"""Generate the home-screen widget layouts (app/src/main/res/layout/widget_*.xml).

Widgets are RemoteViews, so each layout has to spell out every row with its
own ids — RemoteViews resolves ids across the whole tree with no per-include
scoping. Writing eight identical rows by hand is how a typo ends up in row 6;
this script writes them instead.

Every layout has a measured minimum size (in dp) noted at its top. The same
numbers live in WidgetLayouts.kt; the widget shows whichever layout fits the
space the launcher actually gives it. Text height is 1.17 x its size with font
padding off.

Each layout also gets a ``widget_preview_*`` twin with sample data, shown in
the launcher's widget picker (API 31+).

    python3 tools/gen_widget_layouts.py
"""
from __future__ import annotations

from pathlib import Path

