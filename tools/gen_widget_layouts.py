def attrs(**kw: str) -> str:
    return "".join(f'\n    android:{k.replace("__", ":")}="{v}"' for k, v in kw.items())


def text(id_: str, style: str, sample: str | None, **kw: str) -> str:
    kw.setdefault("layout_width", "wrap_content")
    kw.setdefault("layout_height", "wrap_content")
    t = f'\n    android:text="{sample}"' if sample is not None else ""
    return f'<TextView android:id="@+id/{id_}" style="@style/{style}"{attrs(**kw)}{t} />'


def image(id_: str, src: str | None, **kw: str) -> str:
    kw.setdefault("contentDescription", "@null")
    s = f'\n    android:src="{src}"' if src else ""
    return f'<ImageView android:id="@+id/{id_}"{attrs(**kw)}{s} />'


def box(children: list[str], orientation: str, id_: str | None = None, **kw: str) -> str:
    kw.setdefault("layout_width", "match_parent")
    kw.setdefault("layout_height", "wrap_content")
    i = f' android:id="@+id/{id_}"' if id_ else ""
    inner = "\n".join(children)
    return (f'<LinearLayout{i}{attrs(orientation=orientation, **kw)}>\n{inner}\n</LinearLayout>')


def root(children: list[str], comment: str, pad_h: int = 12, pad_v: int = 10, gravity: str = "center_vertical",
         orientation: str = "vertical") -> str:
    inner = "\n".join(children)
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!--\n  GENERATED by tools/gen_widget_layouts.py — edit that, '
            f'not this file.\n\n{comment}\n-->\n'
            f'<LinearLayout {NS}\n    android:id="@android:id/background"'
            f'{attrs(layout_width="match_parent", layout_height="match_parent", orientation=orientation, gravity=gravity, background="@drawable/widget_background", paddingHorizontal=f"{pad_h}dp", paddingVertical=f"{pad_v}dp")}>\n'
            f'{inner}\n</LinearLayout>\n')


def color(kind: str) -> str:
    return "@color/w_up" if kind == "up" else "@color/w_down"


def header(p: bool, title: bool = True, sample: str = "Favorites") -> str:
    kids = []
    if title:
        kids.append(text("w_title", "WidgetText.Title", sample if p else None,
                         layout_width="0dp", layout_weight="1"))
    else:
        kids.append('<View android:layout_width="0dp" android:layout_height="1dp" android:layout_weight="1" />')
    kids.append(text("w_updated", "WidgetText.Dim", "14:05" if p else None))
    kids.append(image("w_refresh", "@drawable/ic_widget_refresh", layout_width="14dp", layout_height="14dp",
                      layout_marginStart="6dp", alpha="0.8"))
    return box(kids, "horizontal", "w_header", gravity="center_vertical", layout_marginBottom="4dp")


def empty(p: bool) -> str:
    return text("w_empty", "WidgetText.Hint", None, layout_width="match_parent", visibility="gone", maxLines="3")


# ── favorites: list with sparklines ─────────────────────────────────────────
def fav_list(p: bool, title: str = "Favorites", sample: list | None = None,
             line: str = "@drawable/widget_preview_spark") -> str:
    rows = []
    for i in range(1, 9):
        s = (sample or SAMPLE)[i - 1]
        rows.append(box([
            text(f"sym_{i}", "WidgetText.Sym", s[0] if p else None, layout_width="44dp"),
            image(f"spark_{i}", line if p else None, layout_width="0dp",
                  layout_height="14dp", layout_weight="1", layout_marginHorizontal="6dp", scaleType="fitXY"),
            text(f"price_{i}", "WidgetText.Price", s[1] if p else None, gravity="end"),
            text(f"chg_{i}", "WidgetText.Change", s[2] if p else None, layout_width="56dp", gravity="end",
                 **({"textColor": color(s[3])} if p else {})),
        ], "horizontal", f"row_{i}", gravity="center_vertical", paddingVertical="3dp",
            # Rows share the height: fewer favorites than room spread out instead of leaving a gap.
            layout_height="0dp", layout_weight="1",
            **({} if not p or i <= 6 else {"visibility": "gone"})))
    return root([header(p, sample=title)] + rows + [empty(p)], """  Favorites, a row per coin: ticker, 7-day sparkline, price, change.
  Rows that do not fit are hidden (WidgetLayouts.FAV_LIST_*): each row is
  3 + 15.2 + 3 = 21.2 dp, the header 11.7 + 4 = 15.7 dp, padding 20 dp.
    N rows = 35.7 + 21.2 N   (2 -> 78, 3 -> 99, 4 -> 121, 6 -> 163, 8 -> 205)
  Width: 44 + 6 + 30 spark + 6 + ~70 price + 56 + 24 padding = ~236, at least 200.""", gravity="top")


