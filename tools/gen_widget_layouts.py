# ── grid of tiles ───────────────────────────────────────────────────────────
def grid(p: bool) -> str:
    lines = []
    n = 0
    for r in range(1, 5):
        tiles = []
        for c in range(1, 5):
            n += 1
            s = SAMPLE[(n - 1) % 8]
            tiles.append(box([
                text(f"tsym_{n}", "WidgetText.Sym.Small", s[0] if p else None),
                text(f"tprice_{n}", "WidgetText.Price", s[1] if p else None, layout_marginTop="3dp"),
                text(f"tchg_{n}", "WidgetText.Change.Tiny", s[2] if p else None, layout_marginTop="2dp",
                     **({"textColor": color(s[3])} if p else {})),
            ], "vertical", f"tile_{n}", layout_width="0dp", layout_height="match_parent", layout_weight="1",
                gravity="center_vertical", background="@drawable/widget_tile", paddingHorizontal="9dp",
                **({} if c == 1 else {"layout_marginStart": "6dp"}),
                **({} if not p or (r <= 2 and c <= 3) else {"visibility": "gone"})))
        lines.append(box(tiles, "horizontal", f"trow_{r}", layout_height="0dp", layout_weight="1",
                         baselineAligned="false", **({} if r == 1 else {"layout_marginTop": "6dp"}),
                         **({} if not p or r <= 2 else {"visibility": "gone"})))
    return root(lines + [empty(p)], """  Favorites as tiles: ticker, price and change in each, up to 4 x 4.
  A tile is 9 + ~52 + 9 = 70 dp wide and 8 + 12.9 + 3 + 15.2 + 2 + 11.7 + 8 = 61 -> 52 dp tall
  (text has slack); tiles and rows are 6 dp apart, padding 12 x 10.
    width  = 24 + 70 c + 6 (c - 1)      height = 20 + 52 r + 6 (r - 1)""", pad_v=10)


# ── top movers: gainers | losers ────────────────────────────────────────────
