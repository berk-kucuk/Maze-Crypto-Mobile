def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("widget_*.xml"):
        old.unlink()
    for name, fn in LAYOUTS.items():
        (OUT / f"widget_{name}.xml").write_text(fn(False), encoding="utf-8")
        (OUT / f"widget_preview_{name}.xml").write_text(fn(True), encoding="utf-8")
    for name, fn in PREVIEW_ONLY.items():
        (OUT / f"widget_preview_{name}.xml").write_text(fn(True), encoding="utf-8")
    print(f"wrote {2 * len(LAYOUTS) + len(PREVIEW_ONLY)} layouts to {OUT}")


if __name__ == "__main__":
    main()
